public class whileLoop {
    
    public static void main(String args[]){
        int i=1;
        while(i<=10){
            System.out.println("mouni "+i);
            int j=1;
            while(j<=3){
                System.out.println("sai "+j);
                j++;
            }
            i++;
        }
        System.out.println("bye"+i);

    }
    
}
